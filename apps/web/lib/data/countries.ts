/**
 * ISO 3166-1 country list used by the country picker.
 *
 * Flags are not hardcoded — they're derived from the two-letter code via
 * `flagFromCode`, which maps each letter to a Unicode Regional Indicator
 * Symbol. A-Z -> 🇦-🇿, so "IN" -> 🇮🇳, "US" -> 🇺🇸, etc.
 */

export interface Country {
  name: string;
  code: string; // ISO 3166-1 alpha-2
}

export function flagFromCode(code: string): string {
  return code
    .toUpperCase()
    .replace(/./g, (char) =>
      String.fromCodePoint(0x1f1e6 - 65 + char.charCodeAt(0)),
    );
}

